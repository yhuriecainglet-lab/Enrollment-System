    private void DELETEActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DELETEActionPerformed
DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    int selectedRow = jTable1.getSelectedRow();
    
    // Check if a row is actually selected
    if (selectedRow >= 0) {
        // FIX: Convert the visual row index to the actual model row index when a sorter/filter is active
        int modelRow = jTable1.convertRowIndexToModel(selectedRow);
        
        // Remove from the model using the correct model index
        model.removeRow(modelRow);
        javax.swing.JOptionPane.showMessageDialog(this, "Item deleted successfully!");
        
        // Clear text fields and reset inputs
        FName.setText("");
        LName.setText("");
        ID.setText("");
        Email1.setText("");
        Gender.setSelectedIndex(0);
        Age.setText("");
        DOB.setDate(null);
        
        NEW.setEnabled(true);

    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Please select a row to delete first.");
    }
    }//GEN-LAST:event_DELETEActionPerformed

