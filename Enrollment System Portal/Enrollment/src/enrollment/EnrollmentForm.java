    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
    DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    int selectedRow = jTable1.getSelectedRow();
    
    if (selectedRow >= 0) {
        // Enable buttons when a row is selected
        UPDATE.setEnabled(true);
        DELETE.setEnabled(true);
        
        NEW.setEnabled(false);
        ADD.setEnabled(false);
           FName.setEnabled(true);
     LName.setEnabled(true);
     ID.setEnabled(true);
     Email1.setEnabled(true);
     Gender.setEnabled(true);
     Age.setEnabled(true);
     DOB.setEnabled(true);
        
        // Auto-fill First and Last Name
        Object nameObj = model.getValueAt(selectedRow, 0);
        if (nameObj != null) {
            String fullName = nameObj.toString();
            String[] nameParts = fullName.split(" ", 2);
            FName.setText(nameParts.length > 0 ? nameParts[0] : "");
            LName.setText(nameParts.length > 1 ? nameParts[1] : "");
        }
        
        // Auto-fill ID
        Object idObj = model.getValueAt(selectedRow, 1);
        ID.setText(idObj != null ? idObj.toString() : "");
        
        // Auto-fill Email
        Object emailObj = model.getValueAt(selectedRow, 2);
        Email1.setText(emailObj != null ? emailObj.toString() : "");
        
        // Auto-fill Gender
        Object genderObj = model.getValueAt(selectedRow, 3);
        if (genderObj != null) {
            Gender.setSelectedItem(genderObj.toString());
        }
        
        // Auto-fill Age
        Object ageObj = model.getValueAt(selectedRow, 4);
        Age.setText(ageObj != null ? ageObj.toString() : "");
        
        // Auto-fill Date of Birth
        Object dateObj = model.getValueAt(selectedRow, 5);
        if (dateObj instanceof java.util.Date) {
            DOB.setDate((java.util.Date) dateObj);
        } else {
            DOB.setDate(null);
        }
    }
    }//GEN-LAST:event_jTable1MouseClicked

