private void setupSearch() {
     DefaultTableModel ob = (DefaultTableModel) jTable2.getModel();
    TableRowSorter<DefaultTableModel> obj = new TableRowSorter<>(ob);
    jTable2.setRowSorter(obj);

    jTextField1.getDocument().addDocumentListener(new javax.swing.event.DocumentListener() {
        @Override
        public void insertUpdate(javax.swing.event.DocumentEvent e) { filterTable(); }
        @Override
        public void removeUpdate(javax.swing.event.DocumentEvent e) { filterTable(); }
        @Override
        public void changedUpdate(javax.swing.event.DocumentEvent e) { filterTable(); }

        private void filterTable() {
            String text = jTextField1.getText().trim();
            if (text.isEmpty() || text.equals("Search")) {
                obj.setRowFilter(null); // show all rows
            } else {
                // Starts-with match: "coli" or "COLIPAN" shows COLIPANO
                obj.setRowFilter(javax.swing.RowFilter.regexFilter(
                    "(?i)^" + java.util.regex.Pattern.quote(text), 0));

                // Contains match (use this instead if you want the keyword
                // to match anywhere in the name, e.g. "pano" shows COLIPANO):
                // obj.setRowFilter(javax.swing.RowFilter.regexFilter(
                //     "(?i)" + java.util.regex.Pattern.quote(text), 0));
            }
        }
    });
}
