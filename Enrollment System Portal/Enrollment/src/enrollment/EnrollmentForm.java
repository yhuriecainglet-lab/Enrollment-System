    private void UPDATE(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_UPDATE
     DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        int selectedRow = jTable1.getSelectedRow();
        
        
        // Check if a row is selected before updating
        if (selectedRow >= 0) {
            // Combine First Name and Last Name with a space
            String firstName = FName.getText().trim();
            String lastName = LName.getText().trim();
            String fullName = firstName + " " + lastName;
            String id = ID.getText().trim();
            String Email2 = Email1.getText().trim();
            String gen = Gender.getSelectedItem().toString();
             String age = Age.getText().trim();
             java.util.Date dob = DOB.getDate();
            
            // Update specific columns (Column 0 = Student Name, Column 1 = ID)
            model.setValueAt(fullName, selectedRow, 0);
            model.setValueAt(id, selectedRow, 1);
            model.setValueAt(Email2, selectedRow, 2);
            model.setValueAt(gen, selectedRow, 3);
            model.setValueAt(age, selectedRow, 4);
            model.setValueAt(dob, selectedRow, 5);
            
            javax.swing.JOptionPane.showMessageDialog(this, "Item updated successfully!");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Please select a row to update first.");
        }
    }//GEN-LAST:event_UPDATE

